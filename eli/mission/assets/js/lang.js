function normalizeLanguage(lang) {
    lang = String(lang || '').trim().toLowerCase();
    return lang === 'en' || lang === 'he' ? lang : '';
}

function getLanguage() {
    const urlParams = new URLSearchParams(window.location.search);
    let lang = normalizeLanguage(urlParams.get('lang'));
    if (!lang) {
        lang = normalizeLanguage(localStorage.getItem('lang')) ||
            normalizeLanguage(document.documentElement.lang) || 'he';
    } else {
        localStorage.setItem('lang', lang);
    }
    document.cookie = `lang=${lang}; max-age=${86400 * 30}; path=/`;
    return lang;
}

function setLanguage(lang) {
    lang = normalizeLanguage(lang) || 'he';
    localStorage.setItem('lang', lang);
    document.cookie = `lang=${lang}; max-age=${86400 * 30}; path=/`;
    const url = new URL(window.location.href);
    url.searchParams.set('lang', lang);
    window.location.href = url.toString();
}
window.setLanguage = setLanguage;

function syncLangPills(currentLang) {
    var heBtn = document.getElementById('mb-lang-he');
    var enBtn = document.getElementById('mb-lang-en');
    if (heBtn && enBtn) {
        heBtn.classList.toggle('is-active', currentLang === 'he');
        enBtn.classList.toggle('is-active', currentLang === 'en');
        heBtn.style.background = '';
        heBtn.style.color = '';
        enBtn.style.background = '';
        enBtn.style.color = '';
    }
    document.querySelectorAll('.lang-btn[data-lang]').forEach(function (btn) {
        btn.classList.toggle('is-active', btn.getAttribute('data-lang') === currentLang);
    });
}

function startHeaderClock() {
    function updateClock() {
        var clockEl = document.getElementById('mb-live-clock');
        if (!clockEl) return;
        var d = new Date();
        var hh = String(d.getHours()).padStart(2, '0');
        var mm = String(d.getMinutes()).padStart(2, '0');
        clockEl.textContent = hh + ':' + mm;
    }
    updateClock();
    if (!window.__mbClockInterval) {
        window.__mbClockInterval = setInterval(updateClock, 1000);
    }
}
window.startHeaderClock = startHeaderClock;

function initLanguage() {
    const currentLang = getLanguage();
    const t = translations[currentLang] || translations['he'];
    
    document.documentElement.lang = currentLang;
    document.documentElement.dir = currentLang === 'he' ? 'rtl' : 'ltr';
    
    var i18nEls = document.querySelectorAll('[data-i18n]');
    i18nEls.forEach(function (el) {
        var key = el.getAttribute('data-i18n');
        if (t[key]) {
            if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
                el.placeholder = t[key];
            } else {
                el.textContent = t[key];
            }
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (t[key]) {
            el.placeholder = t[key];
        }
    });
    
    if (t['page_title']) {
        document.title = t['page_title'];
    }

    // Prefer brand from config.js when available
    if (window.MineralBarApp && typeof MineralBarApp.getBrand === 'function') {
        var brand = MineralBarApp.getBrand(currentLang);
        var brandDemo = (typeof MineralBarApp.getBrandDemo === 'function')
            ? MineralBarApp.getBrandDemo(currentLang)
            : (currentLang === 'he' ? 'ביז1 תצוגה · דמו' : 'Biz1 Showcase · Demo');
        var brandShort = (typeof MineralBarApp.getBrandShort === 'function')
            ? MineralBarApp.getBrandShort(currentLang)
            : (currentLang === 'he' ? 'ביז1' : 'Biz1');
        document.querySelectorAll('[data-i18n="mineral_bar"]').forEach(function (el) {
            el.textContent = brand;
        });
        document.querySelectorAll('[data-i18n="crm_system"]').forEach(function (el) {
            el.textContent = brandDemo;
        });
        document.querySelectorAll('[data-i18n="biz1"]').forEach(function (el) {
            el.textContent = brandShort;
        });
        if (document.title && /Biz1 Showcase|ביז1|מינרל|Mineral/.test(document.title)) {
            document.title = brand + (currentLang === 'he' ? ' — התחברות' : ' — Login');
        }
    }

    const toggleLink = document.getElementById('langToggleLink');
    if (toggleLink) {
        const oppLang = currentLang === 'he' ? 'en' : 'he';
        toggleLink.href = '?lang=' + oppLang;
        toggleLink.textContent = t['lang_toggle'];
    }

    syncLangPills(currentLang);
    startHeaderClock();
    if (window.setGreeting) window.setGreeting();
    try {
      window.dispatchEvent(new CustomEvent('mineralbar:lang', { detail: { lang: currentLang } }));
    } catch (e) { /* ignore */ }
}

