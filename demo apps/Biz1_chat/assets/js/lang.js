function getLanguage() {
  var urlParams = new URLSearchParams(window.location.search);
  var lang = urlParams.get('lang');
  if (!lang) {
    lang = localStorage.getItem('lang') || 'he';
  } else {
    localStorage.setItem('lang', lang);
  }
  if (lang !== 'he' && lang !== 'en') lang = 'he';
  document.cookie = 'lang=' + lang + '; max-age=' + (86400 * 30) + '; path=/';
  return lang;
}

function getBrandName(lang) {
  lang = lang || getLanguage();
  try {
    var cfg = window.Biz1Config && Biz1Config.brand;
    if (cfg) {
      var brand = lang === 'en' ? (cfg.en || cfg.he) : (cfg.he || cfg.en);
      if (brand) return brand;
    }
  } catch (e) { /* ignore */ }
  return (translations[lang] || translations.he).brandName;
}

function resolvePageTitleKey() {
  var path = (location.pathname || '').toLowerCase();
  if (path.indexOf('conversation') !== -1) return 'page_title_messages';
  if (path.indexOf('chat') !== -1) return 'page_title_chat';
  if (path.indexOf('profile') !== -1) return 'page_title_profile';
  return 'page_title';
}

function initLanguage() {
  var currentLang = getLanguage();
  var t = translations[currentLang] || translations.he;
  var brand = getBrandName(currentLang);

  // Keep brand keys in sync with config
  t.brandName = brand;
  t.mineral_bar = brand;
  t.page_title = brand + (currentLang === 'he' ? ' — התחברות' : ' — Login');
  t.page_title_messages = brand + (currentLang === 'he' ? ' — הודעות' : ' — Messages');
  t.page_title_chat = brand + (currentLang === 'he' ? ' — צ׳אט' : ' — Chat');
  t.page_title_profile = brand + (currentLang === 'he' ? ' — פרופיל' : ' — Profile');
  t.crm_system = brand + (currentLang === 'he' ? ' · צ׳אט והודעות' : ' · Chat & Messages');

  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === 'he' ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    if (!t[key]) return;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      if (el.hasAttribute('placeholder') || el.hasAttribute('data-i18n-placeholder')) {
        el.placeholder = t[key];
      } else {
        el.textContent = t[key];
      }
    } else {
      el.textContent = t[key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) el.placeholder = t[key];
  });

  document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-title');
    if (t[key]) el.title = t[key];
  });

  var titleKey = resolvePageTitleKey();
  if (t[titleKey]) document.title = t[titleKey];

  document.querySelectorAll('[data-i18n="brandName"], [data-i18n="mineral_bar"]').forEach(function (el) {
    el.textContent = brand;
  });

  var toggleLink = document.getElementById('langToggleLink');
  if (toggleLink) {
    var oppLang = currentLang === 'he' ? 'en' : 'he';
    toggleLink.href = '?lang=' + oppLang;
    toggleLink.textContent = t.lang_toggle;
  }

  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    var l = btn.getAttribute('data-lang');
    btn.classList.toggle('is-active', l === currentLang);
  });

  if (window.setGreeting) window.setGreeting();
  window.dispatchEvent(new CustomEvent('mineralbar:lang', { detail: { lang: currentLang } }));
}

window.setGreeting = function () {
  var greet = document.getElementById('mb-home-greeting');
  var App = window.Biz1App || window.MineralBarApp;
  if (!greet || !App) return;

  var user = App.getUser() || {};
  var email = App.getEmail() || '';
  var name = user.name || user.user_name || (email ? email.split('@')[0] : window.t('hello'));
  greet.textContent = window.t('hello') + ', ' + name + ' 👋';
};

document.addEventListener('DOMContentLoaded', initLanguage);
initLanguage();

window.t = function (key) {
  var lang = getLanguage();
  var table = translations[lang] || translations.he;
  if (key === 'brandName' || key === 'mineral_bar') return getBrandName(lang);
  return table[key] || key;
};

window.getLanguage = getLanguage;
window.getBrandName = getBrandName;
window.initLanguage = initLanguage;
window.applyI18n = initLanguage;
