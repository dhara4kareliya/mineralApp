const I18n = {
  lang: localStorage.getItem("clinicpulse_lang") || "en",

  t(key, vars = {}) {
    const dict = I18N[this.lang] || I18N.en;
    let text = dict[key] ?? I18N.en[key] ?? key;
    Object.keys(vars).forEach((k) => {
      text = text.replace(`{${k}}`, vars[k]);
    });
    return text;
  },

  setLang(lang) {
    this.lang = lang === "he" ? "he" : "en";
    localStorage.setItem("clinicpulse_lang", this.lang);
    this.apply();
  },

  toggle() {
    this.setLang(this.lang === "en" ? "he" : "en");
  },

  apply() {
    const html = document.documentElement;
    html.lang = this.lang;
    html.dir = this.lang === "he" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      el.textContent = this.t(key);
    });

    document.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = this.t(el.getAttribute("data-i18n-title"));
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = this.t(el.getAttribute("data-i18n-placeholder"));
    });

    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.textContent = this.lang === "en" ? "HE" : "EN";
    });
  },
};

window.I18n = I18n;
window.I18N = I18N;
